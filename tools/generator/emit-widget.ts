/**
 * Emits a Widget: a standalone card placed on a case, a page, or both.
 *
 * With a `list`, the widget follows the recipe of Pega's CASE widget
 * scaffolding (@pega/custom-dx-components, templates/Constellation/Widget/CASE):
 * read a data page, keyed by the case when asked, into a Cosmos Table with a
 * loading state. It goes through the platform facade rather than PCore, adds
 * empty and error states, and refreshes after an assignment is submitted.
 */
import type { ResolvedWidgetSpec } from './define';
import { aboutBlock } from './emit-config';
import { emitStyles } from './emit-component';
import type { GeneratedFile } from './render';

const quote = (value: string) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/* The strings a list widget shows besides its column labels. */
const NO_ITEMS = 'No items';
const LOAD_FAILED = 'Unable to load the list';

export const emitWidgetConfig = (spec: ResolvedWidgetSpec, builtOn = new Date()): string => {
  const authored = spec.properties.map((property) => ({
    name: property.name,
    label: property.label,
    format: property.format,
    ...(property.required ? { required: true } : {}),
    ...(property.config ?? {}),
  }));

  const config = {
    name: spec.componentKey,
    label: spec.label,
    description: spec.description,
    organization: spec.organization,
    version: spec.version,
    library: spec.library,
    allowedApplications: [],
    componentKey: spec.componentKey,
    type: 'Widget',
    subtype: spec.subtype,
    properties: [
      { name: 'heading', label: 'Heading', format: 'TEXT' },
      ...(spec.list
        ? [
            {
              label: 'Data source',
              format: 'GROUP',
              properties: [{ name: 'dataPage', label: 'Data page', format: 'TEXT', required: true }],
            },
          ]
        : []),
      ...authored,
      {
        label: 'Conditions',
        format: 'GROUP',
        properties: [{ name: 'visibility', label: 'Visibility', format: 'VISIBILITY' }],
      },
      ...aboutBlock(spec, builtOn),
    ],
    defaultConfig: { heading: `@L ${spec.label}` },
  };

  return `${JSON.stringify(config, null, 4)}\n`;
};

export const emitWidgetLocalizations = (spec: ResolvedWidgetSpec): string => {
  const strings = [...(spec.list?.columns.map((column) => column.label) ?? []), NO_ITEMS, LOAD_FAILED];
  const fields = Object.fromEntries(strings.map((text) => [text, text]));
  return `${JSON.stringify({ fields }, null, 2)}\n`;
};

export const emitWidgetComponent = (spec: ResolvedWidgetSpec): string => {
  const name = spec.componentName;
  const wrapper = `Styled${name}Wrapper`;
  const { list } = spec;

  const authoredProps = spec.properties
    .map(
      (property) =>
        `  /** ${property.label} */\n  ${property.name}${property.required ? '' : '?'}: ${property.tsType};`,
    )
    .join('\n');
  const authoredTodo = spec.properties.length
    ? `\n  /* TODO: wire up the authored properties. They are accepted and typed,
     but nothing reads them yet. Destructure them from \`props\` as you
     implement each one:
${spec.properties.map((property) => `       ${property.name}  // ${property.label}`).join('\n')} */\n`
    : '';
  const authoredList = spec.properties.length
    ? spec.properties.map((property) => ` *   - ${property.name}: ${property.label}`).join('\n')
    : ' *   (none)';

  const header = `/**
 * ${spec.description}
 *
 * Generated by tools/generator. The props below are emitted from the same spec
 * as config.json, so the property panel and this type cannot drift.
 *
 * Authored properties:
${authoredList}
 */`;

  if (!list) {
    return `import type { ReactNode } from 'react';
import { withConfiguration, Card, CardHeader, CardContent, Text } from '@pega/cosmos-react-core';
import '../shared/create-nonce';
import ${wrapper} from './styles';

${header}
export type ${name}Props = {
  /** Heading shown on the card. */
  heading?: string;
  /** PConnect accessor. */
  getPConnect: () => any;
${authoredProps}
};

export const ${name} = (props: ${name}Props) => {
  const { heading = '' } = props;
${authoredTodo}
  /* TODO: the widget's content. */
  const content: ReactNode = null;

  return (
    <${wrapper}>
      <Card>
        <CardHeader>
          <Text variant='h2'>{heading}</Text>
        </CardHeader>
        <CardContent>{content}</CardContent>
      </Card>
    </${wrapper}>
  );
};

export default withConfiguration(${name});
`;
  }

  const rowType = list.columns.map((column) => `  ${column.field}: string;`).join('\n');
  const toRow = list.columns.map((column) => `        ${column.field}: String(row.${column.field} ?? ''),`).join('\n');
  const columns = list.columns
    .map((column) => `    { renderer: '${column.field}', label: t(${quote(column.label)}) },`)
    .join('\n');
  const queryCall = list.caseParameter
    ? `platform.caseData.query(dataPage, { dataViewParameters: { ${list.caseParameter}: platform.caseInfo.key() } })`
    : 'platform.caseData.query(dataPage)';

  return `import { useCallback, useEffect, useState } from 'react';
import {
  withConfiguration,
  Card,
  CardHeader,
  CardContent,
  EmptyState,
  Progress,
  Table,
  Text,
} from '@pega/cosmos-react-core';
import '../shared/create-nonce';
import { createPlatform } from '../shared/platform';
import ${wrapper} from './styles';

${header}
export type ${name}Props = {
  /** Heading shown on the card. */
  heading?: string;
  /** Data page the list reads${list.caseParameter ? `, keyed by the case through \`${list.caseParameter}\`` : ''}. */
  dataPage: string;
  /** PConnect accessor. */
  getPConnect: () => any;
${authoredProps}
};

/** One table row: the columns the spec names, plus the key the table needs. */
type Row = {
  id: string;
${rowType}
};

export const ${name} = (props: ${name}Props) => {
  const { heading = '', dataPage = '', getPConnect } = props;
${authoredTodo}
  const [rows, setRows] = useState<Row[]>([]);
  const [status, setStatus] = useState<'loading' | 'ready' | 'failed'>('loading');
  const t = (text: string): string => getPConnect().getLocalizedValue(text);

  /* State is only set once the data page answers, never synchronously, so a
     refresh keeps the current rows on screen until the new ones arrive. */
  const load = useCallback(() => {
    const platform = createPlatform(getPConnect);
    ${queryCall}
      .then((response: any) => {
        const data: Record<string, unknown>[] = response?.data?.data ?? [];
        setRows(
          data.map((row, index) => ({
            id: String(index),
${toRow}
          })),
        );
        setStatus('ready');
      })
      .catch(() => setStatus('failed'));
  }, [dataPage, getPConnect]);

  useEffect(() => {
    load();
    /* Refresh after an assignment is submitted; the returned function unsubscribes. */
    return createPlatform(getPConnect).events.on('assignmentSubmission', load);
  }, [load, getPConnect]);

  const columns: { renderer: keyof Row; label: string }[] = [
${columns}
  ];

  let content;
  if (status === 'loading') {
    content = <Progress placement='local' message={createPlatform(getPConnect).text.loadingContent()} />;
  } else if (status === 'failed') {
    content = <EmptyState message={t(${quote(LOAD_FAILED)})} />;
  } else if (rows.length === 0) {
    content = <EmptyState message={t(${quote(NO_ITEMS)})} />;
  } else {
    content = <Table columns={columns} data={rows} />;
  }

  return (
    <${wrapper}>
      <Card>
        <CardHeader>
          <Text variant='h2'>{heading}</Text>
        </CardHeader>
        <CardContent>{content}</CardContent>
      </Card>
    </${wrapper}>
  );
};

export default withConfiguration(${name});
`;
};

/** Sample rows for a list's story: two per column, labelled so tests can find them. */
const sampleRows = (spec: ResolvedWidgetSpec) =>
  [1, 2].map((n) =>
    Object.fromEntries((spec.list?.columns ?? []).map((column) => [column.field, `${column.label} ${n}`])),
  );

export const emitWidgetStories = (spec: ResolvedWidgetSpec): string => {
  const name = spec.componentName;
  const base = [
    `heading: ${quote(spec.label)}`,
    ...spec.properties.map((property) => `${property.name}: ${property.defaultValue ?? "''"}`),
  ];

  if (!spec.list) {
    return `import type { StoryObj } from '@storybook/react-webpack5';
import { createFakeGetPConnect } from '../shared/platform/fake';
import { ${name} } from './index';

export default {
  title: 'Widgets/${spec.label}',
  argTypes: { getPConnect: { table: { disable: true } } },
  parameters: { a11y: { context: '#storybook-root' } },
  component: ${name},
};

type Story = StoryObj<typeof ${name}>;

export const Default: Story = {
  render: (args) => <${name} {...args} getPConnect={createFakeGetPConnect()} />,
  args: {
    ${base.join(',\n    ')},
  },
};
`;
  }

  const args = [...base, "dataPage: 'D_SampleList'"].join(',\n    ');
  const fakeCase = spec.list.caseParameter ? ", caseInfo: { key: 'ORG-APP-WORK C-1' }" : '';

  return `import type { StoryObj } from '@storybook/react-webpack5';
import { installPlatformFake } from '../shared/platform/fake';
import { ${name} } from './index';

/** Rows the sample data page returns. */
const rows = ${JSON.stringify(sampleRows(spec), null, 2)};

export default {
  title: 'Widgets/${spec.label}',
  argTypes: { getPConnect: { table: { disable: true } } },
  parameters: { a11y: { context: '#storybook-root' } },
  component: ${name},
};

type Story = StoryObj<typeof ${name}>;

/* One shared platform double per story, rather than a hand-rolled window.PCore stub. */
export const Default: Story = {
  render: (args) => <${name} {...args} getPConnect={installPlatformFake({ rows${fakeCase} }).getPConnect} />,
  args: {
    ${args},
  },
};

export const Empty: Story = {
  render: (args) => <${name} {...args} getPConnect={installPlatformFake({ rows: []${fakeCase} }).getPConnect} />,
  args: Default.args,
};

export const LoadFailed: Story = {
  render: (args) => (
    <${name} {...args} getPConnect={installPlatformFake({ queryError: new Error('unavailable')${fakeCase} }).getPConnect} />
  ),
  args: Default.args,
};
`;
};

export const emitWidgetTest = (spec: ResolvedWidgetSpec): string => {
  const name = spec.componentName;

  if (!spec.list) {
    return `import { render, screen } from '@testing-library/react';
import { composeStories } from '@storybook/react';
import * as stories from './demo.stories';

const { Default } = composeStories(stories);

test('renders the heading', () => {
  render(<Default />);
  expect(screen.getByText(${quote(spec.label)})).toBeVisible();
});
`;
  }

  const [first] = spec.list.columns;
  const expectedOptions = spec.list.caseParameter
    ? `{ dataViewParameters: { ${spec.list.caseParameter}: 'ORG-APP-WORK C-9' } }`
    : '{}';
  const fakeCase = spec.list.caseParameter ? ", caseInfo: { key: 'ORG-APP-WORK C-9' }" : '';

  return `import { render, screen } from '@testing-library/react';
import { composeStories } from '@storybook/react';
import { installPlatformFake, type PlatformFake } from '../shared/platform/fake';
import * as stories from './demo.stories';
import { ${name} } from './index';

const { Default, Empty, LoadFailed } = composeStories(stories);

let platform: PlatformFake | undefined;
afterEach(() => platform?.restore());

test('lists the rows the data page returns', async () => {
  render(<Default />);
  expect(await screen.findByText(${quote(`${first.label} 1`)})).toBeVisible();
  expect(screen.getByText(${quote(`${first.label} 2`)})).toBeVisible();
});

test('reads the data page the author names${spec.list.caseParameter ? ', keyed by the case' : ''}', async () => {
  platform = installPlatformFake({ rows: []${fakeCase} });
  render(<${name} heading='List' dataPage='D_Chosen' getPConnect={platform.getPConnect} />);
  await screen.findByText(${quote(NO_ITEMS)});

  expect(platform.calls.queries).toEqual([{ dataView: 'D_Chosen', options: ${expectedOptions} }]);
});

test('says so when the data page returns nothing', async () => {
  render(<Empty />);
  expect(await screen.findByText(${quote(NO_ITEMS)})).toBeVisible();
});

test('says so when the data page cannot be read', async () => {
  render(<LoadFailed />);
  expect(await screen.findByText(${quote(LOAD_FAILED)})).toBeVisible();
});

test('stops listening for submissions when it unmounts', async () => {
  platform = installPlatformFake({ rows: [] });
  const { unmount } = render(<${name} heading='List' dataPage='D_Chosen' getPConnect={platform.getPConnect} />);
  await screen.findByText(${quote(NO_ITEMS)});

  expect(platform.calls.subscriptions).toHaveLength(1);
  unmount();
  expect(platform.allUnsubscribed()).toBe(true);
});
`;
};

export const emitWidgetDocs = (spec: ResolvedWidgetSpec): string => {
  const placement = Array.isArray(spec.subtype) ? 'a page or a case' : spec.subtype === 'CASE' ? 'a case' : 'a page';
  const propertyRows = spec.properties.length
    ? spec.properties.map((property) => `| \`${property.name}\` | ${property.format} | ${property.label} |`).join('\n')
    : '| _none_ | | |';
  const listSection = spec.list
    ? `
## List

Reads the data page named in \`dataPage\`${spec.list.caseParameter ? `, passing the case key as \`${spec.list.caseParameter}\`` : ''}, and refreshes after an assignment is submitted.

| Column | Row field |
| --- | --- |
${spec.list.columns.map((column) => `| ${column.label} | \`${column.field}\` |`).join('\n')}
`
    : '';

  return `import { Meta } from '@storybook/addon-docs/blocks';

<Meta title='Widgets/${spec.label}/Docs' />

# ${spec.label}

${spec.description}

Placed on ${placement}.
${listSection}
## Authored properties

| Property | Format | Label |
| --- | --- | --- |
${propertyRows}

\`heading\`${spec.list ? ', `dataPage`' : ''} and \`visibility\` are emitted for every widget${spec.list ? ' with a list' : ''}.

## Notes

Generated by \`tools/generator\`. \`config.json\` and the props type in
\`index.tsx\` come from the same spec, so the property panel cannot offer a
control the component does not accept.
`;
};

export const renderWidget = (spec: ResolvedWidgetSpec, builtOn?: Date): GeneratedFile[] => [
  { name: 'config.json', contents: emitWidgetConfig(spec, builtOn) },
  { name: 'index.tsx', contents: emitWidgetComponent(spec) },
  { name: 'styles.ts', contents: emitStyles(spec) },
  ...(spec.list ? [{ name: 'localizations.json', contents: emitWidgetLocalizations(spec) }] : []),
  { name: 'demo.stories.tsx', contents: emitWidgetStories(spec) },
  { name: 'demo.test.tsx', contents: emitWidgetTest(spec) },
  { name: 'Docs.mdx', contents: emitWidgetDocs(spec) },
];
